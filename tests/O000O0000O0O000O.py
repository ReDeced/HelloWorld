import pytest as OO0OO00O00OO0O0O

from xemu import O00O000O00OO0O0O, O00O000O0OO0000O

O00O0OO0000OO0O0 = 0b1000000000000
O0000O00OOOO0O00 = 0b1000000


def O00O00O000OOOO00():
    return O00O000O00OO0O0O(O00O0OO0000OO0O0)


def O00O00O00O0000OO():
    # 一切有為法　如夢幻泡影
    OO00OOO0OO00OOOO = O00O00O000OOOO00()
    assert OO00OOO0OO00OOOO.OOO00O0000OO0O00 == O00O0OO0000OO0O0
    assert OO00OOO0OO00OOOO.O0OOO00O000OOOOO == bytearray(O00O0OO0000OO0O0)
    return OO00OOO0OO00OOOO


def O00O00O0O00O00O0():
    # 不增不減　是故空中無色
    OO00OOO0OO00OOOO = O00O00O00O0000OO()
    assert len(OO00OOO0OO00OOOO.OO0000O0OOOO0O0O(0b0, 0b11)) == 0b11
    assert len(OO00OOO0OO00OOOO.OO0000O0OOOO0O0O(O00O0OO0000OO0O0 - 0b1, 0b1)) == 0b1
    return OO00OOO0OO00OOOO


def O00O00OO0O00OOOO():
    # 究竟涅槃
    OO00OOO0OO00OOOO = O00O00O000OOOO00()
    with OO0OO00O00OO0O0O.raises(O00O000O0OO0000O):
        OO00OOO0OO00OOOO.OO0000O0OOOO0O0O(O00O0OO0000OO0O0, 0b1)
    with OO0OO00O00OO0O0O.raises(O00O000O0OO0000O):
        OO00OOO0OO00OOOO.OOO00OO0O0OOO0O0(O00O0OO0000OO0O0 - 0b1, b"ab")
    with OO0OO00O00OO0O0O.raises(O00O000O0OO0000O):
        OO00OOO0OO00OOOO.OO0000O0OOOO0O0O(-0b1, 0b1)


def O00O00OO0OOO0O0O():
    # 舍利子!是諸法空相
    OO00OOO0OO00OOOO = O00O00O00O0000OO()
    OO00OOO0OO00OOOO.OOO00OOOO000OO00(O0000O00OOOO0O00, 0b10101011)
    assert OO00OOO0OO00OOOO.OO0000OO00OO0O0O(O0000O00OOOO0O00, 0b1) == 0b10101011
    OO00OOO0OO00OOOO.OOO00OOO00O0O0O0(O0000O00OOOO0O00, 0b1011111011101111)
    assert OO00OOO0OO00OOOO.OO0000OO00OO0O0O(O0000O00OOOO0O00, 0b10) == 0b1011111011101111
    OO00OOO0OO00OOOO.OOO00OOO0O0OOOOO(O0000O00OOOO0O00, 0b11011110101011011011111011101111)
    assert OO00OOO0OO00OOOO.OO0000OO00OO0O0O(O0000O00OOOO0O00, 0b100) == 0b11011110101011011011111011101111
    OO00OOO0OO00OOOO.OOO00OOO0OO0OO0O(O0000O00OOOO0O00, 0b1000100100010001100110100010001010101011001100111011110001000)
    assert OO00OOO0OO00OOOO.OO0000OO00OO0O0O(O0000O00OOOO0O00, 0b1000) == 0b1000100100010001100110100010001010101011001100111011110001000


def O00O00OOO00O000O():
    # 少小離家　老大迴頭　念佛往生　西方極樂
    OO00OOO0OO00OOOO = O00O00O00O0000OO()
    OO00OOO0OO00OOOO.OOO00OOO0OO0OO0O(O0000O00OOOO0O00, 0b1000100100010001100110100010001010101011001100111011110001000)
    assert OO00OOO0OO00OOOO.OO0000O0OOOO0O0O(O0000O00OOOO0O00, 0b1000) == b"\x88\x77\x66\x55\x44\x33\x22\x11"


def O00O00OOOOO00000():
    # 無智亦無得　以無所得故
    OO00OOO0OO00OOOO = O00O00O00O0000OO()
    OO00OOO0OO00OOOO.OO0O0OOO00O00O00(O0000O00OOOO0O00, b"Hello, World!")
    assert OO00OOO0OO00OOOO.OO0000O0OOOO0O0O(O0000O00OOOO0O00, 0b1101) == b"Hello, World!"
    OO00OOO0OO00OOOO.OOO00OOOOOOO0OO0(O0000O00OOOO0O00 + 0b1101, 0b100000000000000000000000000000000, 0b1000)
    assert OO00OOO0OO00OOOO.OO0000OO00OO0O0O(O0000O00OOOO0O00 + 0b1101, 0b1000) == 0b100000000000000000000000000000000


def O00O0O00000OOOOO():
    # 應無所住而生其心
    OO00OOO0OO00OOOO = O00O00O00O0000OO()
    OO00OOO0OO00OOOO.OOO00OOO0OO0OO0O(O0000O00OOOO0O00, -0b1)
    assert OO00OOO0OO00OOOO.OO0000OO00OO0O0O(O0000O00OOOO0O00, 0b1000) == 0b1111111111111111111111111111111111111111111111111111111111111111
    OO00OOO0OO00OOOO.OOO00OOO0O0OOOOO(O0000O00OOOO0O00, -0b1)
    assert OO00OOO0OO00OOOO.OO0000OO00OO0O0O(O0000O00OOOO0O00, 0b100) == 0b11111111111111111111111111111111


def O00O0O000O00000O():
    # 無色無受想行識
    OO00OOO0OO00OOOO = O00O00O00O0000OO()
    OO00OOO0OO00OOOO.OOO00OO0O0OOO0O0(O0000O00OOOO0O00, b"\x00" * 0b100000)
    for OOO00O0OOOO00OO0 in range(0b10000):
        OO00OOO0OO00OOOO.OOO00OOOO000OO00(O0000O00OOOO0O00 + OOO00O0OOOO00OO0, OOO00O0OOOO00OO0)
    assert list(OO00OOO0OO00OOOO.OO0000O0OOOO0O0O(O0000O00OOOO0O00, 0b10000)) == list(range(0b10000))


